"""Native GPT-Live-1 transport; no Gemini events or voice conversion.

Protocol-only support is not a successful provider/voice availability test.
The caller owns microphone capture and must keep sending silence while idle.
"""
from __future__ import annotations

import asyncio
import base64
import inspect
import json
from urllib.parse import urlsplit
import uuid

import aiohttp

LIVE_WS_URL = 'wss://api.openai.com/v1/live/sessions'
MODEL = 'gpt-live-1'
VOICE = 'echo'
SUPPORTED_VOICES = ('echo', 'shida', 'harema')
SAMPLE_RATE = 16000
START_TIMEOUT = 10.0
SEND_TIMEOUT = 5.0
CLOSE_TIMEOUT = 2.0
CALLBACK_TIMEOUT = 2.0
MAX_INPUT_PCM_BYTES = 3200  # The app microphone sends <=100 ms per packet.
MAX_OUTPUT_PCM_BYTES = 64000
MAX_QUEUED_PCM_BYTES = 64000  # Includes a packet currently in the callback.
MAX_QUEUE_PACKETS = 16
MAX_TRANSCRIPT_DELTA_BYTES = 16384
MAX_QUEUED_TRANSCRIPT_BYTES = 32768
MAX_TRANSCRIPT_QUEUE_EVENTS = 32
MAX_EVENT_BYTES = 256 * 1024


class OpenAILiveError(RuntimeError):
    """Only constant, credential-free messages generated by this adapter."""


async def _callback(callback, *args):
    if callback is None:
        return
    result = callback(*args)
    if inspect.isawaitable(result):
        await asyncio.wait_for(result, CALLBACK_TIMEOUT)


def _validate_url(url):
    try:
        parsed = urlsplit(url)
        local = parsed.hostname in {'localhost', '127.0.0.1', '::1'}
        valid = (parsed.scheme == 'wss' or (parsed.scheme == 'ws' and local))
        if (not valid or not parsed.hostname or parsed.username is not None
                or parsed.password is not None or parsed.query or parsed.fragment):
            raise ValueError
        _ = parsed.port
    except (TypeError, ValueError):
        raise OpenAILiveError('Use a secure Live WebSocket URL without credentials or query parameters') from None


def _validate_started(event, expected_voice=VOICE):
    session = event.get('session')
    if not isinstance(session, dict):
        raise OpenAILiveError('Live did not return a resolved session configuration')
    audio = session.get('audio')
    if not isinstance(audio, dict):
        raise OpenAILiveError('Live did not confirm the requested audio configuration')
    if (session.get('model') != MODEL or session.get('status') != 'active'
            or not isinstance(session.get('id'), str) or not session['id']):
        raise OpenAILiveError('Live did not confirm the requested active model')
    if audio.get('output', {}).get('voice') != expected_voice:
        raise OpenAILiveError('Live did not confirm the requested voice')
    audio_format = audio.get('format')
    if not isinstance(audio_format, dict) or audio_format.get('type') != 'audio/pcm' or audio_format.get('rate') != SAMPLE_RATE:
        raise OpenAILiveError('Live did not confirm 16 kHz PCM audio')


async def _read_event(ws):
    message = await ws.receive()
    if message.type != aiohttp.WSMsgType.TEXT:
        raise OpenAILiveError('Live transport closed or sent a non-JSON event')
    try:
        event = json.loads(message.data)
    except (TypeError, ValueError):
        raise OpenAILiveError('Live sent an invalid JSON event') from None
    if not isinstance(event, dict) or not isinstance(event.get('type'), str):
        raise OpenAILiveError('Live sent an invalid event object')
    if event['type'] == 'error':
        # Provider messages may contain authenticated addresses or request data.
        raise OpenAILiveError('Live rejected the request; check server-side model access and configuration')
    return event


async def run_openai_live(*, api_key, persona_instructions, user_events, on_audio, on_cancel,
                          on_transcript=None, on_ready=None, ws_url=LIVE_WS_URL,
                          model=MODEL, voice_name=VOICE, language='ja'):
    """Run one continuous native 16kHz session using the existing app callbacks.

    on_audio(session_token, pcm_bytes, metadata) gets a monotonically increasing
    output_sequence. No turn or interruption boundaries are invented. on_cancel
    only clears that token during session teardown. Callbacks may be async.
    Input events are audio, audio_stream_end (local pause only), or explicit stop.
    Source EOF leaves the receiving session open; app cancellation closes it.
    Text/barge_in are unsupported.
    """
    if not isinstance(api_key, str) or not api_key.strip() or not isinstance(persona_instructions, str) or not persona_instructions.strip():
        raise OpenAILiveError('An explicit API key and character instructions are required')
    if model != MODEL or voice_name not in SUPPORTED_VOICES:
        raise OpenAILiveError('This native experiment requires GPT-Live-1 and a supported Live voice')
    if language not in {'ja', 'en'}:
        raise OpenAILiveError('Unsupported call language')
    _validate_url(ws_url)
    language_rule = ('Speak natural Japanese for this call.' if language == 'ja'
                     else 'Speak natural English for this call.')
    instructions = '\n'.join((
        persona_instructions, language_rule,
        'Keep replies concise. Backchannel policy: Use moderate brief listening acknowledgments.',
        'Interruption policy: Stop speaking when the caller interrupts and listen.',
        'This is a voice-only conversation demo with no external tools or actions. '
        'Do not claim to look up facts, make bookings, or complete external tasks.'))
    token = uuid.uuid4().hex
    ws = None
    started = False
    finalized = False
    cancelled = False
    pending_error = None
    tasks = []
    queue = asyncio.Queue(maxsize=MAX_QUEUE_PACKETS)
    transcripts = asyncio.Queue(maxsize=MAX_TRANSCRIPT_QUEUE_EVENTS)
    queued_bytes = 0
    queued_transcript_bytes = 0
    sequence = 0
    send_lock = asyncio.Lock()

    async def send(event):
        async with send_lock:
            await asyncio.wait_for(ws.send_json(event), SEND_TIMEOUT)

    async def start():
        await send({'type': 'session.start', 'event_id': token,
                    'session': {'model': MODEL, 'instructions': instructions,
                                'audio': {'format': {'type': 'audio/pcm', 'rate': SAMPLE_RATE},
                                          'output': {'voice': voice_name}},
                                'delegation': {'type': 'client'}}})
        while True:
            event = await _read_event(ws)
            if event['type'] == 'session.started':
                _validate_started(event, voice_name)
                return
            if event['type'] != 'info':
                raise OpenAILiveError('Live sent media or commands before session startup was confirmed')

    async def receive():
        nonlocal finalized, queued_bytes, queued_transcript_bytes
        while True:
            event = await _read_event(ws)
            kind = event['type']
            if kind == 'session.output_audio.delta':
                data = event.get('delta')
                if not isinstance(data, str) or len(data) > ((MAX_OUTPUT_PCM_BYTES + 2) // 3) * 4:
                    raise OpenAILiveError('Live sent oversized or invalid audio')
                try:
                    pcm = base64.b64decode(data, validate=True)
                except (TypeError, ValueError):
                    raise OpenAILiveError('Live sent invalid base64 audio') from None
                if len(pcm) % 2 or len(pcm) > MAX_OUTPUT_PCM_BYTES:
                    raise OpenAILiveError('Live sent incomplete or oversized PCM samples')
                if not pcm:
                    continue
                if queued_bytes + len(pcm) > MAX_QUEUED_PCM_BYTES:
                    raise OpenAILiveError('Live playback buffer exceeded its bounded capacity')
                try:
                    queue.put_nowait(pcm)
                except asyncio.QueueFull:
                    raise OpenAILiveError('Live playback buffer exceeded its bounded capacity') from None
                queued_bytes += len(pcm)
            elif kind in {'session.input_transcript.delta', 'session.output_transcript.delta'}:
                if not isinstance(event.get('delta'), str):
                    raise OpenAILiveError('Live sent an invalid transcript')
                text = event['delta']
                size = len(text.encode('utf-8'))
                if size > MAX_TRANSCRIPT_DELTA_BYTES:
                    raise OpenAILiveError('Live sent an oversized transcript')
                if on_transcript is not None:
                    if queued_transcript_bytes + size > MAX_QUEUED_TRANSCRIPT_BYTES:
                        raise OpenAILiveError('Live transcript buffer exceeded its bounded capacity')
                    try:
                        transcripts.put_nowait(('user' if kind == 'session.input_transcript.delta' else 'model', text, size))
                    except asyncio.QueueFull:
                        raise OpenAILiveError('Live transcript buffer exceeded its bounded capacity') from None
                    queued_transcript_bytes += size
            elif kind == 'session.delegation.created':
                # Client delegation requires an actual backend. End explicitly,
                # rather than reporting a fabricated task result to the model.
                raise OpenAILiveError('Live requested backend work; this voice demo has no task backend')
            elif kind == 'session.closed':
                finalized = True
                return
            elif kind == 'session.started':
                raise OpenAILiveError('Live unexpectedly restarted its session')
            # Other informational events neither complete nor interrupt speech.

    async def send_input():
        async for event in user_events:
            if not isinstance(event, dict):
                raise OpenAILiveError('Invalid microphone event')
            kind = event.get('kind')
            if kind == 'stop':
                return
            if kind == 'audio_stream_end':
                # Local source pause, not a Live turn/commit/close event.
                continue
            if kind != 'audio':
                raise OpenAILiveError('GPT-Live native mode accepts microphone audio only')
            pcm = event.get('pcm_s16le')
            if (event.get('sample_rate') != SAMPLE_RATE or event.get('channels') != 1
                    or not isinstance(pcm, bytes) or not pcm or len(pcm) % 2
                    or len(pcm) > MAX_INPUT_PCM_BYTES):
                raise OpenAILiveError('Microphone audio must be 16 kHz mono PCM16 in packets of at most 100 ms')
            # Preserve real silence and continue sending while output plays.
            await send({'type': 'session.input_audio.append',
                        'audio': base64.b64encode(pcm).decode('ascii')})
        # EOF from a microphone/file source is not session termination. The app
        # must cancel this task or send an explicit stop before source EOF.
        await asyncio.Future()

    async def playback():
        nonlocal sequence, queued_bytes
        while True:
            pcm = await queue.get()
            try:
                await _callback(on_audio, token, pcm, {
                    'sample_rate': SAMPLE_RATE, 'channels': 1,
                    'generation_id': token, 'output_sequence': sequence})
                sequence += 1
            finally:
                queued_bytes -= len(pcm)
                queue.task_done()

    async def dispatch_transcripts():
        nonlocal queued_transcript_bytes
        while True:
            role, text, size = await transcripts.get()
            try:
                # UI/network callbacks must not stop receiving native audio.
                await _callback(on_transcript, role, text)
            finally:
                queued_transcript_bytes -= size
                transcripts.task_done()

    async def finalize():
        nonlocal finalized
        if ws is None or finalized or ws.closed:
            return
        async def request_and_read():
            nonlocal finalized
            await send({'type': 'session.close'})
            while True:
                event = await _read_event(ws)
                if event['type'] == 'session.closed':
                    finalized = True
                    return
        try:
            await asyncio.wait_for(request_and_read(), CLOSE_TIMEOUT)
        except Exception:
            pass

    async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=None, sock_connect=START_TIMEOUT)) as http:
        try:
            ws = await asyncio.wait_for(http.ws_connect(
                ws_url, headers={'Authorization': 'Bearer ' + api_key},
                max_msg_size=MAX_EVENT_BYTES, heartbeat=20), START_TIMEOUT)
            await asyncio.wait_for(start(), START_TIMEOUT)
            started = True
            await _callback(on_ready)
            tasks = [asyncio.create_task(receive()), asyncio.create_task(send_input()),
                     asyncio.create_task(playback()), asyncio.create_task(dispatch_transcripts())]
            done, _ = await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
            for task in done:
                task.result()
        except asyncio.CancelledError:
            cancelled = True
        except OpenAILiveError as exc:
            pending_error = exc
        except Exception:
            pending_error = OpenAILiveError('Live session failed; no raw provider details were exposed')
        finally:
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
            # Drain rather than carrying stale session audio into the next call.
            while not queue.empty():
                queue.get_nowait()
                queue.task_done()
            while not transcripts.empty():
                transcripts.get_nowait()
                transcripts.task_done()
            if started:
                try:
                    await _callback(on_cancel, token)
                except Exception:
                    if pending_error is None:
                        pending_error = OpenAILiveError('Live playback cleanup failed')
            await finalize()
            if ws is not None:
                try:
                    await asyncio.wait_for(ws.close(), CLOSE_TIMEOUT)
                except Exception:
                    pass
    if cancelled:
        raise asyncio.CancelledError
    if pending_error is not None:
        raise pending_error from None
    if not finalized:
        raise OpenAILiveError('Live ended without confirming final session closure')
